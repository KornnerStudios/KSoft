	[TestMethod]
	public void CaliburnProviderMatchesPinnedRuntimeContractTest()
	{
		string assemblyName = "CaliburnProviderRuntimeFixture_" + Guid.NewGuid().ToString("N");
		TestRun run = Run("""
			#nullable disable
			using KSoft.PropertyChanged.SourceGeneration;

			public partial class RuntimeCaliburnViewModel : Caliburn.Micro.PropertyChangedBase
			{
				private int mValue;

				public int NotificationCalls { get; private set; }

				[GeneratedPropertyChanged(BackingField = nameof(mValue))]
					public partial int Value { get; set; }

				public override void NotifyOfPropertyChange(string propertyName = null)
				{
					NotificationCalls++;
					base.NotifyOfPropertyChange(propertyName);
				}
			}
			""",
			includeHost: false,
			assemblyName: assemblyName);
		AssertValid(run);

		using var assemblyStream = new MemoryStream();
		var emitResult = run.OutputCompilation.Emit(assemblyStream);
		Assert.IsTrue(
			emitResult.Success,
			string.Join(Environment.NewLine, emitResult.Diagnostics.Select(static diagnostic => diagnostic.ToString())));
		assemblyStream.Position = 0;

		System.Reflection.Assembly assembly =
			System.Runtime.Loader.AssemblyLoadContext.Default.LoadFromStream(assemblyStream);
		Type type = assembly.GetType("RuntimeCaliburnViewModel", throwOnError: true)!;
		var model = (Caliburn.Micro.PropertyChangedBase)Activator.CreateInstance(type)!;
		var propertyNames = new List<string?>();
		model.PropertyChanged += (_, args) => propertyNames.Add(args.PropertyName);
		System.Reflection.PropertyInfo valueProperty = type.GetProperty("Value")!;

		valueProperty.SetValue(model, 1);
		valueProperty.SetValue(model, 1);
		model.IsNotifying = false;
		valueProperty.SetValue(model, 2);

		Assert.AreEqual(2, valueProperty.GetValue(model));
		Assert.AreEqual(1, type.GetProperty("NotificationCalls")!.GetValue(model));
		CollectionAssert.AreEqual(new[] { "Value" }, propertyNames);
	}
