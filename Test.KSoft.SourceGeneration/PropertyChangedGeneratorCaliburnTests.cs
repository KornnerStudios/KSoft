	[TestMethod]
	public void CaliburnProviderSupportsIndirectGenericAncestryAndVirtualNotificationTest()
	{
		TestRun run = Run("""
			#nullable enable
			using KSoft.PropertyChanged.SourceGeneration;

			public abstract class Intermediate<T> : Caliburn.Micro.PropertyChangedBase { }
			public static class Nested<T>
			{
				public abstract class Host : Intermediate<T> { }
			}

			public partial class CaliburnViewModel : Nested<int>.Host
			{
				private int mCount;
				private string? mText;
				private global::System.DayOfWeek mMode;

				[GeneratedPropertyChanged(BackingField = nameof(mCount))]
				public partial int Count { get; set; }

				[GeneratedPropertyChanged(BackingField = nameof(mText))]
				public partial string? Text { get; private set; }

				[GeneratedPropertyChanged(BackingField = nameof(mMode))]
				public partial global::System.DayOfWeek Mode { get; set; }

				public override void NotifyOfPropertyChange(string? propertyName = null)
				{
					base.NotifyOfPropertyChange(propertyName);
				}
			}
			""");

		CompilationUnitSyntax generated = GeneratedCompilationUnit(run);
		Assert.IsFalse(generated.DescendantNodes().OfType<ClassDeclarationSyntax>().Any(
			static declaration => declaration.Identifier.ValueText == "__PropertyChangedEventArgs"));
		Assert.HasCount(
			1,
			generated.DescendantNodes().OfType<MethodDeclarationSyntax>().Where(
				static method => method.Identifier.ValueText == "__PropertyChangedValuesEqual"));
		AssertSetterEquivalent(
			"""
			{
				if (__PropertyChangedValuesEqual(ref this.mCount, value))
				{
					return;
				}

				this.mCount = value;
				global::Caliburn.Micro.PropertyChangedBase propertyChangedNotifier = this;
				if (propertyChangedNotifier.IsNotifying)
				{
					propertyChangedNotifier.NotifyOfPropertyChange(nameof(Count));
				}
			}
			""",
			run,
			"Count");
		AssertSetterEquivalent(
			"""
			{
				if (global::System.Collections.Generic.EqualityComparer<global::System.DayOfWeek>.Default.Equals(this.mMode, value))
				{
					return;
				}

				this.mMode = value;
				global::Caliburn.Micro.PropertyChangedBase propertyChangedNotifier = this;
				if (propertyChangedNotifier.IsNotifying)
				{
					propertyChangedNotifier.NotifyOfPropertyChange(nameof(Mode));
				}
			}
			""",
			run,
			"Mode");
		AccessorDeclarationSyntax textSetter = GeneratedProperty(run, "Text")
			.AccessorList!.Accessors.Single(
				static accessor => accessor.IsKind(SyntaxKind.SetAccessorDeclaration));
		Assert.IsTrue(textSetter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.PrivateKeyword)));
		AssertValid(run);
	}

	[TestMethod]
	public void CaliburnProviderAlwaysNotifySkipsEqualityTest()
	{
		TestRun run = Run("""
			using KSoft.PropertyChanged.SourceGeneration;

			public partial class ForcedCaliburnViewModel : Caliburn.Micro.PropertyChangedBase
			{
				[GeneratedPropertyChanged(AlwaysNotify = true)]
					public partial int Value { get; set; }
			}
			""");
		AssertSourceEquivalent(
			"""
			// <auto-generated/>

			public partial class ForcedCaliburnViewModel
			{
				[global::System.CodeDom.Compiler.GeneratedCodeAttribute("KSoft.PropertyChanged.SourceGeneration.PropertyChangedGenerator", "1.0.0.0")]
				[global::System.Diagnostics.DebuggerNonUserCodeAttribute]
				[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]
				public partial global::System.Int32 Value
				{
					get;
					set
					{
						field = value;
						global::Caliburn.Micro.PropertyChangedBase propertyChangedNotifier = this;
						if (propertyChangedNotifier.IsNotifying)
						{
							propertyChangedNotifier.NotifyOfPropertyChange(nameof(Value));
						}
					}
				}
			}
			""",
			PropertySource(run));
		Assert.IsFalse(
			PropertySource(run).Contains("__PropertyChangedValuesEqual", StringComparison.Ordinal));
		AssertValid(run);
	}

